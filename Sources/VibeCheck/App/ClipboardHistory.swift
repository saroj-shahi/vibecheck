import AppKit
import ApplicationServices
import Carbon.HIToolbox
import Observation

/// One copied thing: plain text, an image, or file references, with where and when it was copied.
struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    enum Content: Codable, Equatable, Sendable {
        case text(String)
        case image(Data)
        case files([URL])
    }
    var id = UUID()
    var content: Content
    var appName: String?
    var date = Date()

    /// One line for the palette.
    var title: String {
        switch content {
        case .text(let text): Self.preview(text)
        case .image(let data): String(localized: "Image, \(ByteCountFormatter.string(fromByteCount: Int64(data.count), countStyle: .file))")
        case .files(let urls): urls.count == 1 ? urls[0].lastPathComponent : String(localized: "\(urls.count) files")
        }
    }

    var symbol: String {
        switch content {
        case .text: "doc.on.clipboard"
        case .image: "photo"
        case .files: "doc"
        }
    }

    /// First non-empty line, trimmed and cut to fit a palette row.
    nonisolated static func preview(_ text: String) -> String {
        let line = text.split(whereSeparator: \.isNewline).lazy
            .map { $0.trimmingCharacters(in: .whitespaces) }.first { !$0.isEmpty } ?? ""
        return line.count > 80 ? String(line.prefix(79)) + "…" : line
    }
}

/// Clipboard history (off by default) and pinned snippets.
///
/// Polls `changeCount` every 0.5 s while on; contents are read only when it changes. Never records
/// concealed / transient / auto-generated items, anything copied while Secure Input is on, or copies made
/// while an ignored app is frontmost. History is memory-only unless "keep across restarts" is on.
/// On macOS 15.4+ reading the general pasteboard can show the "Paste from other apps" prompt; the user
/// decides in System Settings, and Settings → Clipboard says so.
@Observable
@MainActor
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    nonisolated static let maxTextBytes = 64 * 1024
    nonisolated static let maxImageBytes = 5 * 1024 * 1024
    /// Password managers and Keychain Access: never recorded, whatever they put on the pasteboard.
    nonisolated static let defaultIgnored = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.apple.Passwords", "com.apple.keychainaccess",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "org.keepassxc.keepassxc",
        "in.sinew.Enpass-Desktop", "com.nordpass.macos.NordPass", "me.proton.pass.electron",
    ]
    /// Types apps use to say "don't keep this" (nspasteboard.org) plus 1Password's own marker.
    nonisolated static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    @ObservationIgnored private let defaults: UserDefaults
    private(set) var items: [ClipItem] = []

    /// Off by default; asked for on each Mac (not in settings backup).
    var isEnabled: Bool {
        didSet {
            defaults.set(isEnabled, forKey: "clipboardHistory")
            if !isEnabled { clear() }
            updatePolling()
        }
    }
    var limit: Int {
        didSet { defaults.set(limit, forKey: "clipboardHistoryLimit"); items = Array(items.prefix(limit)); save() }
    }
    /// Per Mac, like `isEnabled`: whether copies are written to disk is a decision for this machine.
    var keepAcrossRestarts: Bool {
        didSet { defaults.set(keepAcrossRestarts, forKey: "clipboardKeepAcrossRestarts"); save() }
    }
    /// Bundle ids whose copies are never recorded.
    var ignoredApps: [String] {
        didSet { defaults.set(ignoredApps, forKey: "clipboardIgnoredApps") }
    }
    /// Pinned text, newest first. Kept even with history off (typed or pinned on purpose).
    var snippets: [String] {
        didSet { defaults.set(snippets, forKey: "clipboardSnippets") }
    }

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = 0
    /// Frontmost app at the previous poll: a copy in an ignored app followed by a quick ⌘Tab is still skipped.
    @ObservationIgnored private var previousFront: String?
    @ObservationIgnored private let fileURL: URL

    init(defaults: UserDefaults = .standard, fileURL: URL? = nil) {
        self.defaults = defaults
        self.fileURL = fileURL ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("VibeCheck/clipboard.json")
        isEnabled = defaults.bool(forKey: "clipboardHistory")
        limit = (defaults.object(forKey: "clipboardHistoryLimit") as? Int).map { min(max($0, 10), 200) } ?? 50
        keepAcrossRestarts = defaults.bool(forKey: "clipboardKeepAcrossRestarts")
        ignoredApps = defaults.stringArray(forKey: "clipboardIgnoredApps") ?? Self.defaultIgnored
        snippets = defaults.stringArray(forKey: "clipboardSnippets") ?? []
        if isEnabled && keepAcrossRestarts, let data = try? Data(contentsOf: self.fileURL) {
            items = Array(((try? JSONDecoder().decode([ClipItem].self, from: data)) ?? []).prefix(limit))
        } else {
            try? FileManager.default.removeItem(at: self.fileURL)   // left behind by an earlier setting or crash
        }
    }

    /// Starts polling if history is on (called once at launch).
    func start() { updatePolling() }

    private func updatePolling() {
        timer?.invalidate()
        timer = nil
        guard isEnabled else { return }
        lastChangeCount = NSPasteboard.general.changeCount   // what's already there was copied before history was on
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let front = NSWorkspace.shared.frontmostApplication
        let previous = previousFront
        previousFront = front?.bundleIdentifier
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let ignored = Set(ignoredApps)
        guard previous.map({ !ignored.contains($0) }) ?? true,
              !Self.shouldSkip(types: types, bundleID: front?.bundleIdentifier, ignored: ignored,
                               secureInput: IsSecureEventInputEnabled()),
              let content = Self.read(pasteboard) else { return }
        record(ClipItem(content: content, appName: front?.localizedName))
    }

    func record(_ item: ClipItem) {
        items = Self.inserted(item, into: items, limit: limit)
        save()
    }

    /// Whether a change must not be recorded. Pure, for tests.
    nonisolated static func shouldSkip(types: Set<String>, bundleID: String?, ignored: Set<String>, secureInput: Bool) -> Bool {
        if secureInput || types.isEmpty { return true }
        if let bundleID, ignored.contains(bundleID) { return true }
        return !types.isDisjoint(with: privateTypes)
    }

    /// `item` first; an older copy of the same content is dropped; trimmed to `limit`. Pure, for tests.
    nonisolated static func inserted(_ item: ClipItem, into list: [ClipItem], limit: Int) -> [ClipItem] {
        Array(([item] + list.filter { $0.content != item.content }).prefix(limit))
    }

    /// Files first (Finder also puts names on the pasteboard), then text, then an image; nil when too big.
    private static func read(_ pasteboard: NSPasteboard) -> ClipItem.Content? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty { return .files(urls) }
        if let text = pasteboard.string(forType: .string) {
            return text.utf8.count <= maxTextBytes && !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? .text(text) : nil
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type) { return data.count <= maxImageBytes ? .image(data) : nil }
        }
        return nil
    }

    // MARK: Actions

    /// Puts an item back on the pasteboard (`asText`: file paths as plain text) and moves it to the front.
    func copy(_ item: ClipItem, asText: Bool = false) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let data): pasteboard.setData(data, forType: data.starts(with: [0x89, 0x50, 0x4E, 0x47]) ? .png : .tiff)
        case .files(let urls):
            if asText { pasteboard.setString(urls.map(\.path).joined(separator: "\n"), forType: .string) }
            else { pasteboard.writeObjects(urls as [NSURL]) }
        }
        lastChangeCount = pasteboard.changeCount
        if isEnabled, items.contains(where: { $0.id == item.id }) {
            record(ClipItem(content: item.content, appName: item.appName))
        }
    }

    func copy(snippet: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(snippet, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    /// Copies, then pastes into the frontmost app with ⌘V when VibeCheck has Accessibility.
    /// Returns false when it only copied (no Accessibility yet; asked for once).
    @discardableResult
    static func pasteCopied() -> Bool {
        guard AccessibilityAccess.isTrusted(promptOnce: "clipboardAskedAccessibility") else { return false }
        // Give the deck time to close; it never took focus, so ⌘V lands in the user's app. If another app
        // came forward meanwhile, don't paste into it.
        let target = NSWorkspace.shared.frontmostApplication?.processIdentifier
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target else { return }
            let source = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
                event?.flags = .maskCommand
                event?.post(tap: .cghidEventTap)
            }
        }
        return true
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func pin(_ text: String) {
        snippets = [text] + snippets.filter { $0 != text }
    }

    func unpin(_ text: String) {
        snippets.removeAll { $0 == text }
    }

    func clear() {
        items = []
        try? FileManager.default.removeItem(at: fileURL)
    }

    /// Writes text and file items when "keep across restarts" is on; removes the file otherwise.
    /// shortcut: images stay in memory only (up to 5 MB each would make every save heavy); store them as
    /// separate files if people ask for images across restarts.
    private func save() {
        guard isEnabled, keepAcrossRestarts else { try? FileManager.default.removeItem(at: fileURL); return }
        let kept = items.filter { if case .image = $0.content { false } else { true } }
        guard let data = try? JSONEncoder().encode(kept) else { return }
        try? FileManager.default.createDirectory(at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        // Owner-only: copies can be private.
        if FileManager.default.createFile(atPath: fileURL.path, contents: data, attributes: [.posixPermissions: 0o600]) == false {
            NSLog("VibeCheck: couldn't save clipboard history")
        }
        // createFile keeps an existing file's mode; tighten it in case an older one was wider.
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }
}

/// Accessibility permission, asked for at most once per feature (clipboard paste, keyboard cleaning).
@MainActor
enum AccessibilityAccess {
    /// True when trusted. Otherwise shows macOS's prompt the first time `promptOnce` (a defaults key) is seen.
    static func isTrusted(promptOnce key: String) -> Bool {
        if AXIsProcessTrusted() { return true }
        if !UserDefaults.standard.bool(forKey: key) {
            UserDefaults.standard.set(true, forKey: key)
            let options = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
            return AXIsProcessTrustedWithOptions(options)
        }
        return false
    }
}
